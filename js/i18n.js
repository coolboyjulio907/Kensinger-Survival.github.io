KS.t = function (key, ...args) {
  const lang = (KS.Settings && KS.Settings.get().language) || 'en';
  let s = (KS.STRINGS[lang] && KS.STRINGS[lang][key]);
  if (s === undefined) s = KS.STRINGS.en[key];
  if (s === undefined) return key;
  args.forEach((a, i) => { s = s.replace('{' + i + '}', a); });
  return s;
};

/* localized data fields: pass {en, he} (or any object) -> text for the
   current language, falling back to English */
KS.L = function (obj) {
  if (obj == null || typeof obj !== 'object') return obj;
  const lang = (KS.Settings && KS.Settings.get().language) || 'en';
  return obj[lang] || obj.en || Object.values(obj)[0];
};

/* apply to all [data-i18n] elements (and placeholders/hints) */
KS.applyI18n = function () {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = KS.t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = KS.t(el.dataset.i18nTitle);
  });
};
